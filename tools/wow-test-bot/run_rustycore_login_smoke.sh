# Keep xtrace disabled while credentials and caller-owned runtime values are
# inspected. It is restored only after the complete argv has been assembled;
# the bot password is inherited through the environment, never argv.

password_env_name() {
  local account="$1"
  local suffix=""
  local i ch
  for ((i = 0; i < ${#account}; i++)); do
    ch="${account:i:1}"
    if [[ "$ch" =~ [[:alnum:]] ]]; then
      suffix+="${ch^^}"
    else
      suffix+="_"
    fi
  done
  printf 'WOW_BOT_PASSWORD_%s' "$suffix"
}

ensure_local_password() {
  local account="${WOW_BOT_ACCOUNT:-TESTBOT1@bot.local}"
  if [[ "${WOW_BOT_DETOUR_CHASE_CAPTURE:-0}" =~ ^(1|true|TRUE|yes|YES|on|ON)$ ]]; then
    # The deterministic capture pins TESTBOT2 and must use an explicit
    # caller-owned credential; never persist a generated shared password.
    return
  fi
  local per_account_var
  per_account_var="$(password_env_name "$account")"
  if [[ -n "${WOW_BOT_PASSWORD:-}" || -n "${!per_account_var:-}" ]]; then
    return
  fi
  if [[ "${WOW_BOT_GENERATE_LOCAL_PASSWORD:-1}" =~ ^(0|false|FALSE|no|NO|off|OFF)$ ]]; then
    return
  fi

  local generated
  generated="$(openssl rand -hex 24)"
  umask 077
  if [[ ! -f .env.local ]]; then
    : >.env.local
  fi
  {
    printf '\n# Generated by run_rustycore_login_smoke.sh for local QA only.\n'
    printf 'WOW_BOT_PASSWORD=%q\n' "$generated"
  } >>.env.local
  export WOW_BOT_PASSWORD="$generated"
  echo "Generated local bot password in ignored tools/wow-test-bot/.env.local"
}

