  case "$env_name" in
    WOW_BOT_* | BNET_HOST | BNET_PORT | WORLD_HOST | WORLD_PORT | INSTANCE_HOST | INSTANCE_PORT | REALM_ID)
      caller_runtime_env["$env_name"]="$env_value"
      ;;
  esac
done < <(env -0)
