//! The cast-level initial threat and the player's threat-relevant auras
//! (#1363 slice 10b; moved from the World `session/world_entities/aggro.rs`):
//! C++ `Spell::HandleThreatSpells` (the single-target initial threat after all
//! effects, with `ThreatManager::ForwardThreatForAssistingMe` on the positive
//! path), the canonical threat snapshot of an applied aura, and the
//! `SPELL_AURA_MOD_THREAT` aura sync and hydration the threat modifier reads.
//! The World `cfg!(test)` consumer flag is the host fixture accessor
//! (`SessionHubHostLikeCpp::test_fixtures_ref_like_cpp`), so it keeps its
//! World test-build meaning.

use wow_constants::UnitState;
use wow_core::ObjectGuid;
use wow_entities::{AuraThreatSnapshotLikeCpp, RepresentedAuraEffectAmountLikeCpp};
use wow_world_core::session::SessionHubHostLikeCpp;

use super::SpellEffectHostLikeCpp;
use crate::AuraHostLikeCpp;

/// Represented single-target `Spell::HandleThreatSpells` pass. This runs
/// once after all spell effects, unlike damage/heal threat which is
/// generated by each individual effect.
pub fn apply_spell_initial_threat_like_cpp<H: SpellEffectHostLikeCpp>(
    host: &mut H,
    spell_id: i32,
    caster_guid: ObjectGuid,
    target_guid: ObjectGuid,
    is_positive: bool,
) {
    apply_spell_initial_threat_with_attributes(
        host,
        spell_id,
        caster_guid,
        target_guid,
        is_positive,
        None,
    );
}

pub(crate) fn apply_selected_spell_initial_threat<H: SpellEffectHostLikeCpp>(
    host: &mut H,
    spell_id: i32,
    caster_guid: ObjectGuid,
    target_guid: ObjectGuid,
    is_positive: bool,
    attributes: &[u32; 15],
) {
    apply_spell_initial_threat_with_attributes(
        host,
        spell_id,
        caster_guid,
        target_guid,
        is_positive,
        Some(attributes),
    );
}

fn apply_spell_initial_threat_with_attributes<H: SpellEffectHostLikeCpp>(
    host: &mut H,
    spell_id: i32,
    caster_guid: ObjectGuid,
    target_guid: ObjectGuid,
    is_positive: bool,
    selected_attributes: Option<&[u32; 15]>,
) {
    let Ok(spell_id_u32) = u32::try_from(spell_id) else {
        return;
    };
    let difficulty = host.core().current_map_difficulty_id_like_cpp();
    let difficulty_store = host.hub_ref().catalogs.difficulty_store().cloned();
    // C++ `Spell::HandleThreatSpells` performs this unconditional
    // `!SpellInfo::HasInitialAggro()` return before calling
    // `ThreatManager::AddThreat`. The latter's engaged-owner exception
    // applies to per-effect damage threat, not this cast-level bonus.
    if has_spell_attribute(
        host,
        selected_attributes,
        spell_id,
        difficulty,
        difficulty_store.as_deref(),
        1,
        wow_data::spell::attributes::SPELL_ATTR1_NO_THREAT,
    ) || has_spell_attribute(
        host,
        selected_attributes,
        spell_id,
        difficulty,
        difficulty_store.as_deref(),
        2,
        wow_data::spell::attributes::SPELL_ATTR2_NO_INITIAL_THREAT,
    ) || has_spell_attribute(
        host,
        selected_attributes,
        spell_id,
        difficulty,
        difficulty_store.as_deref(),
        4,
        wow_data::spell::attributes::SPELL_ATTR4_NO_HARMFUL_THREAT,
    ) {
        return;
    }

    let threat_entry = host
        .hub_ref()
        .catalogs
        .spell_threat_entry_like_cpp(spell_id_u32)
        .copied();
    let Some(base_amount) = ({
        let (s, h) = host.split_world_entities_ref();
        s.spell_initial_threat_like_cpp(h, spell_id_u32, threat_entry, caster_guid)
    }) else {
        return;
    };
    if base_amount == 0.0 {
        return;
    }
    if !is_positive {
        let threat_outcome = host
            .core_mut()
            .mutate_world_creature(target_guid, |creature| {
                if !creature.is_alive() {
                    return None;
                }
                if !creature
                    .unit()
                    .subsystems()
                    .combat
                    .owner_can_have_threat_list
                {
                    return None;
                }
                let newly_engaged = !creature.is_in_combat();
                if newly_engaged {
                    creature.enter_combat(caster_guid);
                }
                let combat = &mut creature.unit_mut().subsystems_mut().combat;
                combat.add_threat(caster_guid, base_amount);
                combat
                    .threat_value(caster_guid)
                    .map(|threat_value| (threat_value, newly_engaged))
            })
            .flatten();
        if let Some((threat_value, newly_engaged)) = threat_outcome {
            crate::sync_represented_creature_threat_to_canonical_like_cpp(
                host,
                target_guid,
                caster_guid,
                threat_value,
            );
            if newly_engaged {
                host.publish_spell_pull_attack_start_like_cpp(target_guid, caster_guid);
            }
        }
        return;
    }

    // C++ positive-spell path:
    // `target->GetThreatManager().ForwardThreatForAssistingMe`.
    if has_spell_attribute(
        host,
        selected_attributes,
        spell_id,
        difficulty,
        difficulty_store.as_deref(),
        4,
        wow_data::spell::attributes::SPELL_ATTR4_NO_HELPFUL_THREAT,
    ) {
        return;
    }
    let spell_school_mask = host
        .hub_ref()
        .catalogs
        .spell_school_mask_for_difficulty_like_cpp(
            spell_id_u32,
            host.core().current_map_difficulty_id_like_cpp(),
        );
    let caster_school_threat_mod = if host.player_guid() == Some(caster_guid) {
        hydrate_canonical_threat_relevant_auras_like_cpp(host);
        host.core()
            .mutate_canonical_player_like_cpp(|player| {
                player
                    .unit()
                    .subsystems()
                    .auras
                    .total_aura_multiplier_by_misc_mask_like_cpp(
                        wow_data::spell::aura_types::SPELL_AURA_MOD_THREAT,
                        spell_school_mask,
                    )
            })
            .unwrap_or(1.0)
    } else {
        1.0
    };
    let amount =
        base_amount * threat_entry.map_or(1.0, |entry| entry.pct_mod) * caster_school_threat_mod;
    if amount == 0.0 {
        return;
    }
    let owner_guids = crate::canonical_threatened_by_me_owner_guids_like_cpp(host, target_guid);
    let controlled_mask = UnitState::CONTROLLED.bits();
    let eligible_count = owner_guids
        .iter()
        .filter(|owner_guid| {
            host.core_mut()
                .mutate_world_creature(**owner_guid, |creature| {
                    creature.is_alive() && !creature.unit().has_unit_state(controlled_mask)
                })
                .unwrap_or(false)
        })
        .count();
    let per_owner = (eligible_count != 0).then(|| amount / eligible_count as f32);
    for owner_guid in owner_guids {
        let threat_value = host
            .core_mut()
            .mutate_world_creature(owner_guid, |creature| {
                if !creature.is_alive() {
                    return None;
                }
                let controlled = creature.unit().has_unit_state(controlled_mask);
                let combat = &mut creature.unit_mut().subsystems_mut().combat;
                combat.add_threat(
                    caster_guid,
                    if controlled {
                        0.0
                    } else {
                        per_owner.unwrap_or(0.0)
                    },
                );
                combat.threat_value(caster_guid)
            })
            .flatten();
        if let Some(threat_value) = threat_value {
            crate::sync_represented_creature_threat_to_canonical_like_cpp(
                host,
                owner_guid,
                caster_guid,
                threat_value,
            );
        }
    }
}

fn has_spell_attribute<H: SpellEffectHostLikeCpp>(
    host: &H,
    selected_attributes: Option<&[u32; 15]>,
    spell_id: i32,
    difficulty: u8,
    difficulty_store: Option<&wow_data::DifficultyStore>,
    attribute_word: usize,
    attribute: u32,
) -> bool {
    if let Some(attributes) = selected_attributes {
        return attributes
            .get(attribute_word)
            .is_some_and(|word| word & attribute != 0);
    }
    host.hub_ref().catalogs.spell_store().is_some_and(|store| {
        store.has_attribute_for_difficulty_like_cpp(
            spell_id,
            difficulty,
            difficulty_store,
            attribute_word,
            attribute,
        )
    })
}

pub(crate) fn canonical_threat_aura_snapshot_for_difficulty_like_cpp<H: AuraHostLikeCpp>(
    host: &H,
    spell_id: i32,
    difficulty: u8,
    effect_mask: u32,
    represented_effect_amounts: &[RepresentedAuraEffectAmountLikeCpp],
) -> AuraThreatSnapshotLikeCpp {
    let (state, hub) = host.split_world_entities_ref();
    state.canonical_threat_aura_snapshot_for_difficulty_like_cpp(
        hub,
        spell_id,
        difficulty,
        effect_mask,
        represented_effect_amounts,
    )
}

fn sync_canonical_threat_relevant_aura_like_cpp<H: SessionHubHostLikeCpp>(
    host: &mut H,
    spell_id: i32,
    caster_guid: ObjectGuid,
    slot: u8,
    effect_mask: u32,
    represented_effect_amounts: &[RepresentedAuraEffectAmountLikeCpp],
    apply: bool,
) {
    #[cfg(any(test, feature = "test-fixtures"))]
    let world_test = host.test_fixtures_ref_like_cpp().is_some();
    #[cfg(not(any(test, feature = "test-fixtures")))]
    let world_test = false;
    if !apply {
        host.hub_mut()
            .player_aura_removal_access_like_cpp()
            .remove_player_threat_aura_for_consumer_like_cpp(
                spell_id,
                caster_guid,
                slot,
                effect_mask,
                world_test,
            );
        return;
    }
    let selected_sickness = {
        let hub = host.hub_ref();
        let race_id = hub.player_race_like_cpp();
        // This pass replaces canonical effect registrations. Preserve them
        // when race data cannot distinguish sickness from ordinary auras.
        if race_id == 0 {
            return;
        }
        let Some(races) = hub.catalogs.chr.races_store.as_deref() else {
            return;
        };
        let Some(race) = races.get(u32::from(race_id)) else {
            return;
        };
        if race.res_sickness_spell_id < 0 {
            return;
        }
        race.res_sickness_spell_id > 0 && race.res_sickness_spell_id == spell_id
    };
    let mut hub = host.hub_mut();
    let catalogs = hub.catalogs;
    let spell_store = catalogs.spell_store().map(AsRef::as_ref);
    let difficulty_store = catalogs.difficulty_store().map(AsRef::as_ref);
    hub.player_aura_removal_access_like_cpp()
        .apply_player_threat_aura_for_consumer_like_cpp(
            spell_id,
            caster_guid,
            slot,
            effect_mask,
            selected_sickness,
            false,
            represented_effect_amounts,
            spell_store,
            difficulty_store,
            world_test,
        );
}

pub fn hydrate_canonical_threat_relevant_auras_like_cpp<H: SessionHubHostLikeCpp>(host: &mut H) {
    let Some(auras) = host
        .hub_ref()
        .resolved_player_visible_auras_like_cpp()
        .map(|auras| auras.into_values().collect::<Vec<_>>())
    else {
        return;
    };
    for aura in auras {
        sync_canonical_threat_relevant_aura_like_cpp(
            host,
            aura.spell_id,
            aura.caster_guid,
            aura.slot,
            aura.effect_mask,
            &aura.represented_effect_amounts,
            true,
        );
    }
}
