//! `rustycore-db module apply|remove|purge` (#1444 H6): lock edits, file
//! checks, and a live run on a throwaway MariaDB database.

use super::*;
use crate::migration::module_ops::{
    TOMBSTONE_MARKER, apply_module, lock_with_tombstones, lock_without_tombstone, plan_removal,
    purge_module, purge_statements, retain_sql, retained_data,
};

const COUNTS: &str = "CREATE TABLE mod_it_mod_counts (guid BIGINT UNSIGNED PRIMARY KEY, kills INT UNSIGNED NOT NULL DEFAULT 0);\n";
const SEED: &str = "INSERT INTO mod_it_mod_counts (guid, kills) VALUES (1, 2);\n";
const PURGE: &str = "DROP TABLE IF EXISTS mod_it_mod_counts;\n";

/// A repository root with the module's data/sql and the lock compose.py
/// would write for it (module `it.mod`, enabled after `a.first`).
fn workspace(tag: &str, first_has_sql: bool) -> (PathBuf, String) {
    let unique = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let root = std::env::temp_dir().join(format!(
        "rustycore-module-ops-{tag}-{}-{unique}",
        std::process::id()
    ));
    let sql = root.join("modules/it_mod/data/sql");
    fs::create_dir_all(sql.join("characters")).unwrap();
    fs::create_dir_all(sql.join("purge")).unwrap();
    fs::write(sql.join("characters/1.sql"), COUNTS).unwrap();
    fs::write(sql.join("characters/2.sql"), SEED).unwrap();
    fs::write(sql.join("purge/characters.sql"), PURGE).unwrap();
    let first = if first_has_sql {
        format!(
            "\n[module.sql]\nmin_core_schema = \"1\"\nsource = \"modules/first/data/sql\"\n\n[[module.sql.migration]]\ndatabase = \"characters\"\nversion = \"1\"\ndescription = \"first\"\nfile = \"characters/1.sql\"\nsha256 = \"{}\"\n",
            sha256_hex("CREATE TABLE mod_a_first_x (id INT);\n")
        )
    } else {
        String::new()
    };
    let lock = format!(
        "# Generated by tools/modules/compose.py. Do not edit by hand.\nsource_api = \"2\"\n\n[[module]]\nid = \"a.first\"\nenabled_order = 0\n{first}\n[[module]]\nid = \"it.mod\"\nenabled_order = 1\n\n[module.sql]\nmin_core_schema = \"1\"\nsource = \"modules/it_mod/data/sql\"\n\n[[module.sql.migration]]\ndatabase = \"characters\"\nversion = \"1\"\ndescription = \"counts\"\nfile = \"characters/1.sql\"\nsha256 = \"{}\"\n\n[[module.sql.migration]]\ndatabase = \"characters\"\nversion = \"2\"\ndescription = \"seed\"\nfile = \"characters/2.sql\"\nsha256 = \"{}\"\n\n[[module.sql.purge]]\ndatabase = \"characters\"\nfile = \"purge/characters.sql\"\nsha256 = \"{}\"\n",
        sha256_hex(COUNTS),
        sha256_hex(SEED),
        sha256_hex(PURGE)
    );
    (root, lock)
}

/// The lock after `rustycore-module remove` and `sync`: no `[[module]]` for
/// it.mod, the tombstone block kept.
fn without_checkout(lock: &str) -> String {
    let marker = lock.find(TOMBSTONE_MARKER).unwrap();
    format!(
        "# Generated by tools/modules/compose.py. Do not edit by hand.\nsource_api = \"2\"\n\n{}",
        &lock[marker..]
    )
}

fn core_manifest(database: DatabaseKind) -> MigrationManifest {
    MigrationManifest {
        format: 1,
        baselines: DatabaseKind::ALL
            .into_iter()
            .map(|kind| BaselineRequirement {
                database: kind,
                marker_table: if kind == database {
                    "it_marker".into()
                } else {
                    "absent".into()
                },
                content_version: None,
                cache_id: None,
            })
            .collect(),
        migrations: vec![Migration {
            component: "core".into(),
            database: DatabaseKind::Auth,
            version: "1".into(),
            description: "core".into(),
            file: "core.sql".into(),
            sha256: sha256_hex("SELECT 1;\n"),
            state: MigrationState::Archived,
            adopt_query: None,
        }],
        root: PathBuf::new(),
    }
}

#[test]
fn remove_writes_a_tombstone_that_compose_keeps_and_purge_drops_it() {
    let (root, lock) = workspace("lock", false);
    let plan = plan_removal(&lock, &root, "it.mod").unwrap();
    assert_eq!(
        plan.retained,
        PathBuf::from("modules/.retired/it.mod/data/sql")
    );
    assert!(
        plan.lock.starts_with(lock.trim_end()),
        "the generated part is untouched"
    );
    assert!(plan.lock.contains(&format!(
        "\n\n{TOMBSTONE_MARKER}\n[[tombstone]]\nid = \"it.mod\""
    )));
    let schema = ModuleSchema::from_lock(&plan.lock).unwrap();
    let tombstone = schema.tombstone("it.mod").unwrap();
    assert_eq!(
        tombstone.sql.as_ref().unwrap().source,
        "modules/.retired/it.mod/data/sql"
    );
    // Removing again is refused: it is tombstoned once the checkout is gone.
    let removed = without_checkout(&plan.lock);
    assert!(
        plan_removal(&removed, &root, "it.mod")
            .err()
            .unwrap()
            .to_string()
            .contains("already removed")
    );

    // The retained copy is what purge reads, verified and guarded.
    let sql = ModuleSchema::from_lock(&lock)
        .unwrap()
        .active("it.mod")
        .unwrap()
        .sql
        .clone()
        .unwrap();
    retain_sql(&root, &sql, &plan).unwrap();
    let schema = ModuleSchema::from_lock(&removed).unwrap();
    assert_eq!(
        purge_statements(&schema, &root, "it.mod", DatabaseKind::Characters).unwrap(),
        vec!["DROP TABLE IF EXISTS mod_it_mod_counts".to_string()]
    );
    assert!(
        purge_statements(&schema, &root, "it.mod", DatabaseKind::World)
            .unwrap()
            .is_empty()
    );
    // A composed module cannot be purged.
    let composed = ModuleSchema::from_lock(&plan.lock).unwrap();
    assert!(purge_statements(&composed, &root, "it.mod", DatabaseKind::Characters).is_err());

    let purged = lock_without_tombstone(&removed, "it.mod").unwrap();
    assert!(!purged.contains(TOMBSTONE_MARKER));
    assert!(ModuleSchema::from_lock(&purged).unwrap().is_empty());
    assert_eq!(
        lock_with_tombstones(&lock, &[]),
        lock,
        "no tombstone, no block"
    );
    fs::remove_dir_all(root).unwrap();
}

#[test]
fn changed_or_unguarded_files_are_refused_before_any_database_work() {
    let (root, lock) = workspace("files", false);
    fs::write(
        root.join("modules/it_mod/data/sql/characters/2.sql"),
        "INSERT INTO mod_it_mod_counts VALUES (9, 9);\n",
    )
    .unwrap();
    let error = plan_removal(&lock, &root, "it.mod")
        .err()
        .unwrap()
        .to_string();
    assert!(
        error.contains("changed since modules.lock.toml recorded it"),
        "{error}"
    );

    // A purge script that reaches a core table is refused by the guard even
    // when its checksum matches the lock.
    let (root2, lock2) = workspace("guard", false);
    let evil = "DROP TABLE characters;\n";
    fs::write(
        root2.join("modules/it_mod/data/sql/purge/characters.sql"),
        evil,
    )
    .unwrap();
    let lock2 = lock2.replace(&sha256_hex(PURGE), &sha256_hex(evil));
    let plan = plan_removal(&lock2, &root2, "it.mod").unwrap();
    let sql = ModuleSchema::from_lock(&lock2)
        .unwrap()
        .active("it.mod")
        .unwrap()
        .sql
        .clone()
        .unwrap();
    retain_sql(&root2, &sql, &plan).unwrap();
    let schema = ModuleSchema::from_lock(&without_checkout(&plan.lock)).unwrap();
    let error = purge_statements(&schema, &root2, "it.mod", DatabaseKind::Characters)
        .unwrap_err()
        .to_string();
    assert!(error.contains("refused by the module SQL guard"), "{error}");
    fs::remove_dir_all(root).unwrap();
    fs::remove_dir_all(root2).unwrap();
}

#[tokio::test]
#[ignore = "requires a disposable live MariaDB; set RUSTYCORE_DB_IT_USER and optional HOST/PORT/PASS"]
async fn live_mariadb_module_apply_remove_and_purge() -> Result<()> {
    let Some(user) = std::env::var("RUSTYCORE_DB_IT_USER").ok() else {
        eprintln!("skipping: RUSTYCORE_DB_IT_USER is not set");
        return Ok(());
    };
    let host = std::env::var("RUSTYCORE_DB_IT_HOST").unwrap_or_else(|_| "127.0.0.1".into());
    let port = std::env::var("RUSTYCORE_DB_IT_PORT").unwrap_or_else(|_| "3306".into());
    let password = std::env::var("RUSTYCORE_DB_IT_PASS").unwrap_or_default();
    let server = MySqlPoolOptions::new()
        .max_connections(1)
        .connect(&format!(
            "mysql://{user}:{password}@{host}:{port}?ssl-mode=DISABLED"
        ))
        .await?;
    let unique = SystemTime::now().duration_since(UNIX_EPOCH)?.as_nanos();
    let database_name = format!("rustycore_module_it_{}_{}", std::process::id(), unique);
    sqlx::query(&format!(
        "CREATE DATABASE `{database_name}` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci"
    ))
    .execute(&server)
    .await?;
    let pool = MySqlPoolOptions::new()
        .max_connections(3)
        .connect(&format!(
            "mysql://{user}:{password}@{host}:{port}/{database_name}?ssl-mode=DISABLED"
        ))
        .await?;
    let characters = DatabaseKind::Characters;
    sqlx::query("CREATE TABLE it_marker (id INT PRIMARY KEY)")
        .execute(&pool)
        .await?;
    let core = core_manifest(characters);
    // The core history table, as `rustycore-db migrate` leaves it.
    migrate_database(&pool, &core, characters).await?;

    let (first_root, lock) = workspace("live", true);
    let schema = ModuleSchema::from_lock(&lock)?;
    let manifest = core.with_module_schema(&schema)?;
    let report = inspect_database(&pool, &manifest, characters).await?;
    assert!(
        !report.compatible,
        "pending module SQL keeps the server from starting"
    );

    // enabled_order: a.first comes first.
    let error = apply_module(
        &pool,
        &manifest,
        &schema,
        &first_root,
        "it.mod",
        characters,
        true,
    )
    .await
    .unwrap_err()
    .to_string();
    assert!(error.contains("comes earlier in enabled_order"), "{error}");
    fs::remove_dir_all(first_root)?;

    let (root, lock) = workspace("live2", false);
    let schema = ModuleSchema::from_lock(&lock)?;
    let manifest = core.with_module_schema(&schema)?;
    let dry = apply_module(
        &pool, &manifest, &schema, &root, "it.mod", characters, false,
    )
    .await?;
    assert_eq!(dry.pending, vec!["1".to_string(), "2".to_string()]);
    assert!(dry.tables.is_empty(), "a dry run changes nothing");
    assert!(dry.history.is_empty());

    let applied =
        apply_module(&pool, &manifest, &schema, &root, "it.mod", characters, true).await?;
    assert_eq!(applied.tables, vec!["mod_it_mod_counts".to_string()]);
    assert_eq!(applied.history, vec!["1".to_string(), "2".to_string()]);
    let kills: i64 =
        sqlx::query_scalar("SELECT CAST(kills AS SIGNED) FROM mod_it_mod_counts WHERE guid = 1")
            .fetch_one(&pool)
            .await?;
    assert_eq!(kills, 2);
    assert!(
        inspect_database(&pool, &manifest, characters)
            .await?
            .compatible
    );
    let again = apply_module(&pool, &manifest, &schema, &root, "it.mod", characters, true).await?;
    assert!(again.pending.is_empty(), "apply is idempotent");

    // A plain server (no module history accepted) refuses this database.
    assert!(
        !inspect_database(
            &pool,
            &core.with_module_schema(&ModuleSchema::empty())?,
            characters
        )
        .await?
        .compatible
    );

    // remove: tables and history stay; the tombstoned lock is accepted.
    let plan = plan_removal(&lock, &root, "it.mod")?;
    let sql = schema.active("it.mod").unwrap().sql.clone().unwrap();
    retain_sql(&root, &sql, &plan)?;
    fs::remove_dir_all(root.join("modules/it_mod"))?;
    let removed = without_checkout(&plan.lock);
    let tombstoned = ModuleSchema::from_lock(&removed)?;
    let manifest = core.with_module_schema(&tombstoned)?;
    let kept = retained_data(&pool, "it.mod", characters).await?;
    assert_eq!(kept.tables, vec!["mod_it_mod_counts".to_string()]);
    assert_eq!(kept.history.len(), 2);
    let report = inspect_database(&pool, &manifest, characters).await?;
    assert!(report.compatible, "{:?}", report.problems);

    // purge: dry run first, then the reviewed DROP and the history go.
    let dry = purge_module(&pool, &tombstoned, &root, "it.mod", characters, false).await?;
    assert_eq!(
        dry.statements,
        vec!["DROP TABLE IF EXISTS mod_it_mod_counts".to_string()]
    );
    assert_eq!(dry.tables.len(), 1, "a dry run drops nothing");
    let purged = purge_module(&pool, &tombstoned, &root, "it.mod", characters, true).await?;
    assert!(purged.tables.is_empty());
    assert!(purged.history.is_empty());
    let after = lock_without_tombstone(&removed, "it.mod")?;
    let manifest = core.with_module_schema(&ModuleSchema::from_lock(&after)?)?;
    assert!(
        inspect_database(&pool, &manifest, characters)
            .await?
            .compatible
    );

    pool.close().await;
    sqlx::query(&format!("DROP DATABASE `{database_name}`"))
        .execute(&server)
        .await?;
    server.close().await;
    fs::remove_dir_all(root)?;
    Ok(())
}
