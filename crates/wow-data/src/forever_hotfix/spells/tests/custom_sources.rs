#[test]
fn unit_condition_serializes_all_52_bytes_and_dispatches_without_external_id_or_locale() {
    let row = rows::unit_condition(0xf1234567);
    let expected = [
        0x20, 0x00, 0x00, 0x80, 0x80, 0x81, 0x82, 0x83, 0x84, 0x85, 0x86, 0x87, 0xf0, 0xf1, 0xf2,
        0xf3, 0xf4, 0xf5, 0xf6, 0xf7, 0x30, 0x00, 0x00, 0x80, 0x31, 0x00, 0x00, 0x80, 0x32, 0x00,
        0x00, 0x80, 0x33, 0x00, 0x00, 0x80, 0x34, 0x00, 0x00, 0x80, 0x35, 0x00, 0x00, 0x80, 0x36,
        0x00, 0x00, 0x80, 0x37, 0x00, 0x00, 0x80,
    ];
    assert_eq!(super::super::custom_sources::unit_condition(&row), expected);
    let data = Arc::new(
        SpellRecords {
            unit_conditions: vec![row],
            ..Default::default()
        }
        .finish(
            Default::default(),
            Default::default(),
            6,
            Default::default(),
            Default::default(),
            &Db2HotfixRemovalStoreLikeCpp::default(),
        )
        .unwrap(),
    );
    let stores = super::super::SpellHotfixStores { data };
    for locale in [0, 6, 255] {
        assert_eq!(
            stores
                .record(SPELL_TABLE_HASHES[48], 0xf1234567, locale)
                .unwrap(),
            expected
        );
    }
    assert!(stores.record(SPELL_TABLE_HASHES[48], 7, 6).is_none());
}

